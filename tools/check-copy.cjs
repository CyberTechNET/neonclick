    ok(!/payment|donut|invoice|VKWebAppOrder/i.test(vSec),
      'платёжных окон моста в разделе нет: VIP — не точка монетизации (досье §6.4)');
    /* Связь VIP и гильдии должна оставаться косметической: инвариант 3 раздела 13d
       («роль — справка от VK, а не купленная отметка»). Строка, где они встречаются,
       ровно одна, и это подстановка класса значка. Появится вторая — гильдия станет
       продаваемой, и закреп «надбавка персональная, а не соревнование» соврёт. */
    const vipGuildLines = GAME.split(/\r?\n/).filter((l) => /vip/i.test(l) && /guild/i.test(l));
    ok(vipGuildLines.length === 1 && vipGuildLines.every((l) => /classList|is-vip/.test(l)),
      'VIP касается гильдии только значком: других строк, где они вместе, нет',
      vipGuildLines.map((l) => l.trim()));
