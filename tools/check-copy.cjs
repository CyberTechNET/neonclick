console.log('\n[4] Чего ни один текст обещать не может');
{
  const BANNED = /слот|рулетк|покер|джекпот|выигрыш\s+(деньг|рубл)|реальн\w*\s+(приз|выплат)|на деньги/i;
  for (const b of blocks) {
    const m = BANNED.exec(b.text);
    ok(!m, b.variant + ' / ' + b.field + ': нет слотов, джекпота и обещаний выплаты деньгами', m && m[0]);
    // «Казино» допустимо только в отрицании: «это не казино».
    const bad = [...b.text.matchAll(/казино/gi)]
      .filter((x) => !/не\s+казино/i.test(b.text.slice(Math.max(0, x.index - 6), x.index + 8)));
    ok(bad.length === 0, b.variant + ' / ' + b.field + ': «казино» встречается только как отрицание', bad.length);
  }
  const ARCADE = /выигр|заработай|доход\s+в\s+рубл|приз\s+ден/i;
  const slB = at('Б', 'Слоган');
  ok(slB && !ARCADE.test(slB.text), 'Б / слоган: не обещает выигрыша — это аркадный вариант', slB && slB.text);
}

console.log('\n[5] Досье ссылается на эти блоки');
for (const f of ['Слоган', 'Краткое описание', 'Подробное описание']) {
  ok(md.includes('| ' + f + ' | \u0441\u043c. \u00a74, \u0431\u043b\u043e\u043a \u00ab' + f + '\u00bb'),
    '§1: поле «' + f + '» указывает на одноимённый блок §4');
}
/* НОВАЯ КАРТОЧКА 54839632 (21.10.2026). Номер — единственное, что в этих бумагах
   меняется заменой, а не словами, и потому он же — самое дешёвое место для
   тишины: досье, описывающее подачу на отозванную карточку, читается ровно так
   же уверенно, как актуальное. Три факта ниже держат форму, пригодную для
   копирования: живой адрес только новый, тип назван полем кабинета, отозванный
   номер оставлен только протоколом. */
ok(md.includes('`54839632`'), '§1: ID приложения зафиксирован (54839632)');
ok(md.includes('| Тип приложения | «Мини-приложение» |'),
  '§1: тип карточки записан полем кабинета, а не памятью о форме создания');
ok(/Отозванная карточка \| `54836005`/.test(md) && md.includes('подлежит удалению'),
  '§1: прежняя карточка записана отдельной строкой и названа отозванной, а не вытрета');
ok(md.includes('### 2.1'), '§2.1: решение по категории «Азартные» записано вместе с последствиями');

console.log('\n[6] Числа сверены с боевым артефактом, а не только с исходниками');
{
  /* В кабинет уходит _site/, собранный tools/build-release.cjs, а не дерево
     исходников. Если артефакт устарел, досье описывает игру, которой никто
     не увидит: числа из game.js уже одни, а на витрине VK живёт другой билд.
     Поэтому те же факты вытаскиваются второй раз — из _site/ — и сравниваются. */
  const siteGame = path.join(ROOT, '_site', 'game.js');
  const siteHtml = path.join(ROOT, '_site', 'index.html');
  if (!fs.existsSync(siteGame) || !fs.existsSync(siteHtml)) {
    log('\u23f3 _site/ не собран: сверка с артефактом пропущена (npm run build:release перед отправкой)');
  } else {
    const ART = factsFrom(readText(siteGame), readText(siteHtml), '_site');
    const diff = Object.keys(CODE)
      .filter((k) => JSON.stringify(CODE[k]) !== JSON.stringify(ART[k]))
      .map((k) => k + ': ' + JSON.stringify(CODE[k]) + ' \u2192 ' + JSON.stringify(ART[k]));
    ok(diff.length === 0, '_site/ несёт те же числа, что описывает досье', diff);
  }
}

console.log('\n[7] Игра внутри себя обещает то же, что витрина');
{
  /* Группа [4] читает только §4 — она сторожит то, что модератор видит на витрине.
     Но ва-банк и гильдия живут внутри игры, и подпись «Испытай удачу» приехала бы
     туда молча, вместе с правкой разметки, без единого изменения §4. Поэтому те же
     запреты применяются к исходной разметке, к CFG.guild.roster и к боевому
     артефакту: досье обещает кабинет, а игрок читает игру. */
  const GAME = readText(path.join(ROOT, 'game.js'));
  const HTML = readText(path.join(ROOT, 'index.html'));
  const PROMISE = /удач|испыт|джекпот|выигр|на деньги|разбогат|приз\s+(ден|руб)/i;
  const label = (re, what) => {
    const m = re.exec(HTML);
    ok(!!m, what + ' имеет подпись в разметке', m && m[1]);
    ok(m && !PROMISE.test(m[1]), what + ': называет действие, не обещает удачу и выигрыш', m && m[1]);
    return m && m[1];
  };
  const cta = label(/id="riskCta">([^<]*)</, 'кнопка ва-банка');
  label(/risk__sub">([^<]*)</, 'подзаголовок ва-банка');

  const rosterSrc = (GAME.match(/guild:\s*\{[\s\S]*?\n\s*\}/) || [''])[0];
  const roster = [...rosterSrc.matchAll(/\{\s*id:\s*(\d+)\s*,\s*name:\s*'([^']*)'\s*\}/g)];
  ok(roster.length > 0, 'CFG.guild.roster опирается на настоящее сообщество', roster.length);
  ok(roster.every((m) => Number(m[1]) > 0 && m[2].trim().length > 0),
    'у каждой гильдии положительный id и непустое имя', roster.map((m) => m[0]));
  const orphan = roster.filter((m) => !md.includes(m[1]));
  ok(orphan.length === 0, 'каждый id гильдии назван в досье (§1)', orphan.map((m) => m[1]));

  /* Ловушка №1 из vk-integration.js, перенесённая в бумаги: сообщество в ссылке
     пишется с минусом, а рука копирует положительный vk_group_id. Проверяются обе
     формы — правильная обязана быть, битой быть нельзя. */
  const readme = readText(path.join(ROOT, 'README.md'));
  const gid = roster.length ? roster[0][1] : null;
  const APP = '54839632';   // карточка 21.10.2026
  const DEAD = '54836005';  // отозванная: тип «Игра», гильдии не даёт
  for (const [where, text] of [['досье', md], ['README п.3', readme]]) {
    ok(!!gid && text.includes('app' + APP + '_-' + gid),
      where + ': ссылка запуска несёт минус перед id сообщества');
    ok(!!gid && !text.includes('app' + APP + '_' + gid),
      where + ': битой ссылки без минуса в нём нет');
    /* Отпечатанная ссылка переживает тот день, когда карточку сменили: админ
       копирует её из документа, не зная, что номер отозван. Полная форма
       (https://) копируется в браузер целиком, поэтому запрещена именно она —
       голому упоминанию номера в протоколе здесь делать нечего, он остаётся
       текстом без схемы. */
    ok(!!gid && !text.includes('https://vk.com/app' + DEAD),
      where + ': отозванная ссылка не оставлена в копируемой форме');
  }

  /* ТИП КНОПКИ ДЕЙСТВИЯ. Две причины быть в чекере, а не в памяти:

     1) Ярлык правильного типа по документации VK не сверян — dev.vk.com в день
        правки отдавал 404 и баннер «технические работы». Значит, бумагам нельзя
        называть тип положительно: названное слово, которого нет в выпадающем
        списке кабинета, читается как инструкция и исполняется. Требование
        отрицательное — тип без полей URL-схемы и сторов, — и оно проверяется
        глазами на месте. Отсюда запрет на возврат ярлыка.
     2) Кабинет 10.10.2026 показал не только готовую конфигурацию «Открыть
        мобильное приложение» с https-ссылкой в поле URL-схемы и пустыми
        сторами, но и реакцию на её сохранение: три подсказки «Укажите хотя бы
        одну ссылку». То есть тип закрыт для проекта самим кабинетом, а не
        нашим решением, и состояние кнопки по умолчанию — выключена. Оба факта
        обязаны пережить следующую настройку, иначе они будут переоткрыты
        вручную. */
  const LABEL = /тип\s+«открыть мини-приложение»/i;
  for (const [where, text] of [['досье', md], ['README п.3', readme]]) {
    ok(!LABEL.test(text),
      where + ': тип кнопки не назван ярлыком, которого не сверяли с кабинетом');
    ok(text.includes('«Открыть мобильное приложение»'),
      where + ': запрещённый тип назван прямо (проверен скриншотом кабинета)');
    ok(/URL-схем/i.test(text) && text.includes('App Store'),
      where + ': запрет на поле URL-схемы и сторы записан');
    ok(/хотя бы одну ссылку/i.test(text),
      where + ': запись кабинета о сохранении типа зафиксирована');
    ok(/выключен/i.test(text),
      where + ': состояние кнопки по умолчанию — выключена');
    ok(/не определяет гильдию/i.test(text),
      where + ': сказано, что гильдию включает добавление в сообщество, а не кнопка');
  }

  /* ПРИЧИНЫ ОТСУТСТВИЯ ГИЛЬДИИ. Их две, и раньше они выдавались за одну: ветка
     id <= 0 не различала мост и vk_group_id, поэтому приложение, отлично
     подключённое к VK, писало «нет подключения к VK» — и админ чинил не то.
     Теперь подписи разные и в коде, и в бумагах, и обязаны оставаться
     синхронными: досье, описывающее интерфейс другими словами, бесполезно ровно
     в тот момент, когда его читают вместо вкладки. */
  ok(GAME.indexOf("'запуск не из сообщества'") > -1 && GAME.indexOf("'нет подключения к VK'") > -1,
    'game.js: «в VK, но не из сообщества» и «моста нет» — разные подписи вкладки');
  for (const [where, text] of [['досье', md], ['README п.3', readme]]) {
    ok(/запуск не из сообщества/.test(text) && /нет подключения к VK/i.test(text),
      where + ': обе причины названы теми же словами, что и в интерфейсе');
    ok(/суффикс/.test(text) && /m\.vk\.com\/app54836005_-/.test(text),
      where + ': симптом срезанного суффикса и негативный контроль редиректа записаны');
  }

  /* ДОСТУПНОСТЬ К УСТАНОВКЕ. П.3 начинался с кнопки «Добавить», которой в живом
     кабинете сообщества не оказалось: приложения нет в списке «Мои приложения».
     Это состояние раньше привязки, и оно обязано быть записано, иначе следующий
     админ снова придёт нажимать отсутствующую кнопку и решит, что сломан
     суффикс в ссылке. */
  ok(/«Мои приложения»/.test(readme) && /ни NeonClick, ни 54836005/i.test(readme),
    'README п.3: запись кабинета — приложения нет в списке установки сообщества');
  ok(/два NeonClick/i.test(readme) && /Состояние для пользователей/i.test(readme),
    'README п.3: перечислены причины отсутствия — аккаунт, сообщество, статус');
  ok(/формой\s+входа/i.test(readme),
    'README п.3: отмечено, что извне это не проверяется (страницы отдают форму входа)');
  ok(/«Мои приложения»/.test(md) && /списк\S*\s+установк/i.test(md),
    'досье §5: снимок гильдии требует доступности к установке, а не только п.3');

  /* ТИП ПРИЛОЖЕНИЯ. Четвёртая причина, найденная 20.10.2026, и первая, которая
     объясняет наблюдение целиком: аккаунт свой, состояние «Вкл», а строки в
     сообществе всё равно нет. Она же закрывает маршрут «починить привязку»: VK
     документально не отдаёт играм ни vk_group_id, ни vk_viewer_group_role, так
     что гильдия на карточке 54836005 не оживёт ни при каком состоянии кабинета.
     Факт проверяется через includes, а не регэкспом: урок про \w и кириллицу уже
     оплачен, а сторож, матчащий «Игра» через [A-Za-z], светился бы зелёным
     навечно — ровно тогда, когда его бы сняли с документа. */
  for (const [where, text] of [['досье', md], ['README п.3', readme]]) {
    ok(text.includes('не используется в играх'),
      where + ': цитата VK о запрете vk_group_id/vk_viewer_group_role играм записана');
    ok(text.includes('«Игра»') && text.includes('«Мини-приложение»'),
      where + ': тип приложения назван и противопоставлен нужному');
    ok(text.includes('launch-параметров'),
      where + ': сказано, что рантайм id не хранит и пересборка не нужна');
  }
  ok(readme.includes('четырёх проверок') && readme.includes('четыре проверки') &&
     md.includes('четырёх причин'),
    'причин отсутствия гильдии в обоих документах четыре, а не три');
  /* Ловушка обязана быть записана не только там, где её заметили, но и там, где
     её совершают. П.3 — это вскрытие; п.1 — единственное место, где тип ещё
     можно выбрать правильно. Оставить факт только в вскрытии — значит гарантировать
     повторение на следующей карточке. */
  ok(readme.includes('обязательно выбрать тип «Мини-приложение»'),
    'README п.1: тип приложения назван на том шаге, где он выбирается');

  /* УДАЛЕНИЕ ОШИБОЧНОЙ КАРТОЧКИ. Тип не перевыпускается, поэтому единственная
     починка — новая карточка плюс удаление старой, а кнопка удаления у «Игры» и у
     мини-приложения лежит на РАЗНЫХ страницах (Размещение против Настроек). Кабинет
     в день правки недоступен, значит путь существует только в документации и обязан
     пережить тот день, когда админ откроет кабинет и станет искать кнопку наугад —
     иначе он первым делом пойдёт в «Настройки», где её нет, и решит, что удалять
     нечем. Второй сторож держит порядок: удаление необратимо, а регистрация — нет,
     поэтому сначала вторая карточка. Оба правила — через includes по фразам,
     лежащим целиком внутри одной строки. */
  ok(readme.includes('dev.vk.com/admin/apps-list') &&
     readme.includes('Удалённую игру нельзя восстановить') &&
     /блок «Удаление мини-приложения»/.test(readme),
    'README п.1: путь удаления назван для обоих типов и помечен как необратимый');
  ok(readme.includes('сначала новая карточка') && readme.includes('потом удаление'),
    'README п.1: удаление ставится после регистрации карточки правильного типа');

  /* СМЕНА КАРТОЧКИ НЕ ЗАКРЫВАЕТ П.3. 54839632 сняла четвёртую причину и только
     её: аккаунт, сообщество и статус проверяются на каждом номере заново, потому
     что это свойства пары «карточка × сообщество», а не карточки. Без этого
     сторожа запись «карточка создана» легко доедается как «гильдия работает», и
     админ приходит за скриншотом на карточку, которой в сообществе нет. */
  ok(readme.includes('Тип у неё сверен') && readme.includes('«Мини-приложение»'),
    'README п.1: тип новой карточки сверен колонкой «Тип», а не выведен из формы создания');
  ok(readme.includes('регистрация состоялась') &&
     readme.includes('единственная из четырёх') &&
     readme.includes('порядок пункта 3 на новой карточке тот же'),
    'README п.3: снята только четвёртая причина, первые три повторяются на новом номере');
  ok(readme.includes('Замер 21.10.2026') && readme.includes('отвечает 200 и редиректа не делает'),
    'README п.3: негативный контроль суффикса повторён на новой карточке');
  ok(md.includes('а с 21.10.2026 — `app54839632`') && md.includes('не наследится со старой'),
    '§2.1: решение оператора по категории перенесено на новую карточку');
  ok(md.includes('в «не готово», но не в «закрыто»') &&
     md.includes('кадр «Гильдии» по-прежнему снимается только после README п.3'),
    'досье §5: кадр «Гильдии» снимается после README п.3, а не после регистрации');


  /* Артефакт обязан говорить то же, что исходники: старый «Играть» в _site/
     уехал бы в кабинет незаметно для любой проверки по дереву репозитория. */
  const siteHtml = path.join(ROOT, '_site', 'index.html');
  if (!fs.existsSync(siteHtml)) {
    log('\u23f3 _site/ не собран: сверка подписи кнопки с артефактом пропущена');
  } else {
    const siteCta = /id="riskCta">([^<]*)</.exec(readText(siteHtml));
    ok(!!siteCta && siteCta[1] === cta, 'в _site/ кнопка ва-банка подписана тем же словом',
      siteCta && siteCta[1]);
  }
}

console.log('\n===== ТЕКСТЫ ВИТРИНЫ ' + passed + ' ok / ' + failed + ' fail =====');
if (failed) {
  console.log('Описание разошлось с кодом или с бюджетом поля. Править текст в §4, а не цифру в заголовке блока: цифру пересчитает этот же прогон.');
}
process.exit(failed ? 1 : 0);
