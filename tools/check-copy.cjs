#!/usr/bin/env node
/* ==========================================================================
 * tools/check-copy.cjs — сверка текстов витрины (§4 досье) с кодом игры.
 *
 * Почему отдельный скрипт, а не глаза. Досье обещает кабинету конкретные
 * числа: 3 раунда в сутки, ставка 25/50/100%, минимум 1000, 5/10/15 минут,
 * +1000 и +500, крит ×5, ×2 на 5 минут. Каждое из них живёт в CFG игры, и
 * изменение баланса молча делает описание неправдой — ровно тот класс лжи,
 * за который заявку разворачивают уже после релиза.
 *
 * Вторая половина — длина. Кабинет режет поля по своему лимиту, а в досье
 * каждая цифра подписана рядом с текстом. Подпись, которую никто не
 * пересчитывает, устаревает в тот момент, когда кто-то поправил одну букву.
 * Поэтому текст вытаскивается из блока цитаты, длина считается по кодовым
 * точкам и сверяется с заявленной, а заявленная обязана влезать в бюджет поля.
 *
 * Это НЕ часть npm test: ничего не запускает, браузер не нужен, зависимостей
 * нет (только node:fs/path). Живёт рядом с check-moderation-kit.cjs — оба
 * отвечают на вопрос «можно ли отправлять бумаги», а не «работает ли игра».
 *
 * Группы [1]–[7] — витрина и бумаги вокруг неё. Группа [8] — материалы сообщества
 * (assets/community/guild-launch.md): тексты проекта, которые читает подписчик внутри
 * VK. Предмет тот же: число, пересказанное из CFG, обязано совпасть с CFG.
 * С 22.10.2026 в группу [8] входит VIP: числа читаются из CFG.vip, подписи — из
 * renderVip(), а границы раздела 13e, на которые тот ссылался в комментарии с первого
 * дня, мерятся по срезу кода, а не по обещанию.
 *
 * Группа [9] — assets/marketing/: копия, уезжающая наружу. Отличие от [8] не в словах,
 * а в единице измерения: наружу каждый пост уезжает один, и раскрытия, сказанные в
 * соседнем разделе, с ним не едут. Поэтому гранулярность объявляет сам файл
 * (Текст: каждый раздел | весь файл), а числа читаются тем же cfgFacts, что и в [8].
 *
 * Запуск:
 *   node tools/check-copy.cjs
 *   npm run check:copy
 * ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DOSSIER = path.join(ROOT, 'assets', 'moderation', 'application.md');

let passed = 0, failed = 0;
const log = (...a) => console.log('  ' + a.join(' '));
const ok = (cond, name, extra) => {
  if (cond) { passed++; log('\u2705 ' + name); }
  else { failed++; log('\u274c ' + name + (extra !== undefined ? '  \u2192 ' + JSON.stringify(extra) : '')); }
};

const readText = (p) => fs.readFileSync(p, 'utf8');
function grab(src, re, what) {
  const m = re.exec(src);
  if (!m) throw new Error('check-copy: не прочитано из кода: ' + what);
  return m;
}

/* --------------------------------------------------------------------------
 * Факты игры: описание витрины их пересказывает, значит обязано совпасть.
 * ------------------------------------------------------------------------ */
/** Список вида [a, b, c]; каждый член — произведение множителей («10 * 60000»). */
const terms = (s) => s.replace(/^\[|\]$/g, '').split(',')
  .map((t) => t.trim().split('*').reduce((a, b) => a * Number(b.trim()), 1));
/** Одиночное значение вида «5 * 60 * 1000» — произведение всех множителей. */
const product = (s) => s.trim().split('*').reduce((a, b) => a * Number(b.trim()), 1);

/**
 * Все числа, которые витрина пересказывает, из одной пары файлов.
 * Вызывается дважды: по исходникам и по боевому артефакту _site/ — см. [6].
 */
function factsFrom(gameSrc, htmlSrc, where) {
  const g = (re, what) => grab(gameSrc, re, where + ': ' + what);
  const h = (re, what) => grab(htmlSrc, re, where + ': ' + what);
  /* Комментарии в CFG поясняют человеку, но для парсера это мусор: строка
     «stakes: [0.25, 0.5, 1], // доля баланса» без срезания коммента
     распадается на шесть «членов списка» вместо трёх. */
  const risk = g(/risk:\s*\{[\s\S]*?\n\s*\}/, 'CFG.risk')[0].replace(/\/\/[^\n]*/g, '');
  const field = (key, what) => {
    const m = new RegExp(key + ':\\s*(.+)$', 'm').exec(risk);
    if (!m) throw new Error('check-copy: не прочитано из ' + where + ' CFG.risk: ' + what);
    return m[1].trim().replace(/,$/, '').trim();
  };
  return {
    logo: g(/logo:\s*'([^']+)'/, 'THAMES.neon.copy.logo')[1],
    critMult: Number(g(/crit:\s*\{[^}]*mult:\s*(\d+)/, 'CFG.crit.mult')[1]),
    boostMult: Number(g(/boost:\s*\{[^}]*mult:\s*(\d+)/, 'CFG.boost.mult')[1]),
    boostMin: Math.round(product(g(/boost:\s*\{\s*ms:\s*([0-9*\s]+),/, 'CFG.boost.ms')[1]) / 60000),
    adReward: Number(g(/freeCoinsReward:\s*(\d+)/, 'CFG.freeCoinsReward')[1]),
    shareReward: Number(g(/share:\s*\{\s*reward:\s*(\d+)/, 'CFG.share.reward')[1]),
    sharePerDay: Number(g(/share:\s*\{[^}]*perDay:\s*(\d+)/, 'CFG.share.perDay')[1]),
    riskPerDay: Number(field('perDay', 'perDay')),
    minStake: Number(field('minStake', 'minStake')),
    stakes: terms(field('stakes', 'stakes')).map((x) => Math.round(x * 100)),
    boostPrize: terms(field('boostMs', 'boostMs')).map((ms) => Math.round(ms / 60000)),
    upClick: h(/card__title">(Сила клика)</, 'название апгрейда клика')[1],
    upAuto: h(/card__title">(Авто-майнинг)</, 'название авто-майнинга')[1]
  };
}

const CODE = factsFrom(
  readText(path.join(ROOT, 'game.js')),
  readText(path.join(ROOT, 'index.html')),
  'исходники'
);

/**
 * Все числа, которые пересказывают тексты, прочитанные ОДНИМ чтением одного файла.
 *
 * Функция живёт на уровне модуля, а не по копии в каждой группе, потому что [8]
 * (тексты подписчику) и [9] (тексты наружу, в свои каналы) пересказывают одни и те
 * же поля одного CFG. Две копии парсера расходятся молча и ровно в ту сторону, где
 * число уже напечатано, — тот же класс ошибки, из-за которого PROMISE объявлен здесь
 * же, а не внутри [7].
 *
 * Каждая регэкспа возвращает ПОСЛЕДНЮЮ группу, а не первую: они начинаются с
 * ограничителя (^|[,{\s]), и m[1] вернул бы его. Эта ошибка уже была оплачена в
 * группе [8], где «cd.includes('' + ' монет')» истинно на любом документе и весь
 * сторож проходит зелёным по пустоте.
 */
function cfgFacts(src) {
  const die = (what) => { throw new Error('check-copy: не прочитано из CFG: ' + what); };
  /* Одинарные и многострочные блоки читаются одной формой: ленивый поиск до первой
     закрывающей скобки уместен, потому что ни в одном из нужных блоков нет вложенных
     объектов — только массивы порогов (tiers, stakes, boostMs). */
  const blk = (key, what) => {
    const m = new RegExp(key + ':\\s*\\{[\\s\\S]*?\\}').exec(src);
    return m ? m[0].replace(/\/\/[^\n]*/g, '') : die(what);
  };
  const num = (b, key, what) => {
    const m = new RegExp('(^|[,{\\s])' + key + ':\\s*(-?[\\d.]+)', 'm').exec(b);
    return m ? m[m.length - 1].trim() : die(what);
  };
  const arr = (b, key, what) => {
    const m = new RegExp(key + ':\\s*\\[([^\\]]*)\\]').exec(b);
    if (!m) return die(what);
    return m[1].split(',').map((s) => s.trim()).filter(Boolean);
  };
  /* Одиночное поле вне именованного блока (freeCoinsReward, share.reward): тем же
     последним группы, что num, чтобы не заводить вторую манеру чтения. */
  const one = (s, re, what) => {
    const m = re.exec(s);
    return m ? m[m.length - 1] : die(what);
  };
  const raid = blk('raid', 'raid'), vipB = blk('vip', 'vip'),
        risk = blk('risk', 'risk'), crit = blk('crit', 'crit');
  const min = (s) => Math.round(product(s) / 60000);
  return {
    guildMult: num(raid, 'guildMult', 'raid.guildMult'),
    honorPer: num(raid, 'honorPer', 'raid.honorPer'),
    boostCost: num(raid, 'boostCost', 'raid.boostCost'),
    boostMin: min((/\bboostMs:\s*([0-9*\s]+?)(?:,|\n)/.exec(raid) || [, ''])[1]),
    perDay: num(raid, 'perDay', 'raid.perDay'),
    tiers: [...raid.slice(raid.indexOf('tiers:')).matchAll(/\[\s*(\d+)\s*,\s*'([^']*)'\s*\]/g)]
      .map((m) => [Number(m[1]), m[2]]),
    critMult: num(crit, 'mult', 'crit.mult'),
    riskPerDay: num(risk, 'perDay', 'risk.perDay'),
    minStake: num(risk, 'minStake', 'risk.minStake'),
    /* Ставки и выплаты рисуются игроку процентами и минутами, а не долями и
       миллисекундами: пересказ обязан совпадать с тем видом, в каком число видит
       человек, иначе «0.25» в посте спорил бы с «25%» на экране. */
    stakesPct: arr(risk, 'stakes', 'risk.stakes').map((s) => Math.round(Number(s) * 100)),
    boostMinList: arr(risk, 'boostMs', 'risk.boostMs').map(min),
    vipCost: num(vipB, 'cost', 'vip.cost'),
    vipDays: num(vipB, 'days', 'vip.days'),
    vipDailyMin: min((/dailyMs:\s*([0-9*\s]+?)(?:,|\n)/.exec(vipB) || [, ''])[1]),
    /* Награды. Витрина называет их числами (§4 вариант А), а таблица меры [9] этих
       полей не знала вовсе: пост, где кто-то напишет «+1500 монет за ролик», проходил
       зелёным, потому что меряющий корпус список просто не включал награду. Поля
       читаются здесь, а не в [9], потому что мера одна на два предмета — см. [10]. */
    adReward: one(src, /freeCoinsReward:\s*(\d+)/, 'CFG.freeCoinsReward'),
    shareReward: one(src, /share:\s*\{\s*reward:\s*(\d+)/, 'CFG.share.reward'),
    sharePerDay: one(src, /share:\s*\{[^}]*perDay:\s*(\d+)/, 'CFG.share.perDay'),
  };
}


/* Русская морфология: описание пишет «силу клика», а UI — «Сила клика», поэтому
   апгрейды сверяются по основам слов, а не по полной форме. Основа = слово без
   двух последних букв, но не короче трёх букв: «Сила» → «Сил», «клика» → «клика». */
const stems = (phrase) => phrase.toLowerCase().split(/[\s-]+/)
  .map((w) => w.slice(0, Math.max(3, w.length - 2)));
const hasUpgrade = (text, phrase) => stems(phrase).every((st) => text.toLowerCase().includes(st));

/* ЗАПРЕТ НА ОБЕЩАНИЯ. Одно правило на две группы проверок: [7] меряет им витрину
   (§4 досье, читает модератор), [8] — материалы сообщества (читает подписчик).
   Держать его внутри [7] значило бы переписывать во второй группе, а переписанное
   правило расходится с оригиналом молча и ровно в ту сторону, где обещание уже
   напечатано. Живёт здесь, на уровне модуля. */
const PROMISE = /удач|испыт|джекпот|выигр|на деньги|разбогат|приз\s+(ден|руб)/i;

/* Граница «что уходит читателю» — одна на группы [8] и [9]. Проза файла о самих
   запретах перечисляет запрещённые слова списком, и мерить её теми же правилами
   значит требовать немой грамоты; но переписанное правило расходится с оригиналом
   молча и ровно в ту сторону, где текст уже напечатан. Отсюда на уровне модуля,
   тем же правом, что и PROMISE. */
const spokenOf = (t, stopRe) => {
  const L = t.split(/\r?\n/);
  const at = stopRe ? L.findIndex((l) => stopRe.test(l)) : -1;
  return L.slice(0, at >= 0 ? at : L.length)
    .filter((l) => /^\s*>/.test(l) || /^\s*\|/.test(l)).join('\n');
};

/** То же содержимое, но без разметки цитаты и схлопнутое в одну строку — для
 *  литеральных проверок: проза переносится по ширине, и includes() ломается сначала
 *  о перенос, потом о маркер «> » (обе смерти оплачены группой [8]). stopRe —
 *  регулярка заголовка, с которого текст перестаёт быть адресованным читателю:
 *  таблица источников обязана называть то, чего в коде нет. */
const flatOf = (t, stopRe) => {
  const L = t.split(/\r?\n/);
  const at = stopRe ? L.findIndex((l) => stopRe.test(l)) : -1;
  return L.slice(0, at >= 0 ? at : L.length)
    .filter((l) => /^\s*>/.test(l) || /^\s*\|/.test(l))
    .map((l) => l.replace(/^\s*>\s?/, ''))
    .join(' ').replace(/\s+/g, ' ').trim();
};

/** Экранирование строки, прочитанной в коде, для подстановки в регулярку (разделители
 *  подписи VIP берутся из renderVip(), а не переписываются в чекер). */
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Страж раскола. includes() ловит отсутствие числа, но не половину лжи: если закреп
 * пишет «×1,35», а сторис осталось при «×1,25», документ по-прежнему содержит
 * правильное значение и проверка проходит. Поэтому берётся множество ВСЕХ чисел
 * рядом с единицей, и оно обязано состоять ровно из значения CFG. Общая на [8] и [9]:
 * внешняя копия расходится с внутренней ровно тем же движком.
 *
 * Граница \b после кириллицы не работает: \w — это [A-Za-z0-9_], поэтому «ь» и пробел
 * оба не-символьные, и \b между ними не возникает. Урок, оплаченный в шапке
 * negctl-copy.cjs и повторённый здесь: формы должны быть достаточно уникальны сами.
 */
const unitOf = (text, re, want, what) => {
  const seen = [...new Set([...text.matchAll(re)].map((m) => m[1]))];
  ok(seen.length > 0 && seen.every((v) => v === String(want)),
    what + ': везде ровно ' + want + ', а не набор ' + (seen.join('/') || 'пусто'), seen);
};

/**
 * Разрез файла на самостоятельные тексты по заголовкам «## N.» — для тех проверок,
 * которые обязаны выполняться для ОДНОГО поста. Файловая проверка на этом месте
 * врёт: текст, где один пост раскрывает отрицательное матожидание, а второй нет,
 * проходит целиком, и ровно так наружу уезжает пост без раскрытия. Наружу каждый
 * пост уходит один, поэтому и мерится один.
 *
 * skipRe — регулярка заголовка раздела, который текстом для читателя не является
 * (провенанс чисел и разбор самих запретов): там запрещённые слова стоят списком.
 */
const sectionsOf = (t, skipRe) => {
  const L = t.split(/\r?\n/);
  const at = L.map((l, i) => (/^##\s*\d+\./.test(l) ? i : -1)).filter((i) => i >= 0);
  const out = [];
  for (let k = 0; k < at.length; k++) {
    const title = L[at[k]].replace(/^##\s*\d+\.\s*/, '').trim();
    if (skipRe && skipRe.test(L[at[k]])) continue;
    const to = k + 1 < at.length ? at[k + 1] : L.length;
    const text = L.slice(at[k], to).join('\n');
    if (/\S/.test(spokenOf(text))) out.push({ title, text });
  }
  return out;
};

/** Роль внешнего текста, объявленная самим файлом (assets/marketing/*.md):
 *  к журналу запреты копии не применяются, и мере это не повод начинать. */
const roleOf = (t) => ((/^[ \t]*Роль:[ \t]*(\S+)/m).exec(t) || [, ''])[1].trim();

/** Плоские тексты файлов, объявленных копией. Критерий тот же, что у [9], и
 *  функция одна: [8] и [9] уже платили за вторую копию парсера, расходящуюся
 *  молча и ровно там, где число уже напечатано. */
const copyFlats = (dir) => fs.readdirSync(dir).filter((f) => /\.md$/i.test(f))
  .map((f) => [f, readText(path.join(dir, f))])
  .filter(([, t]) => roleOf(t) === 'копия')
  .map(([, t]) => flatOf(t));


/* --------------------------------------------------------------------------
 * Разбор §4: блоки «Слоган / Краткое описание / Подробное описание».
 * ------------------------------------------------------------------------ */
const BUDGET = { 'Слоган': 60, 'Краткое описание': 250, 'Подробное описание': 1000 };
const WORDS = { 1: 'одна', 2: 'две', 3: 'три', 4: 'четыре', 5: 'пять' };

/** Текст блока цитаты: «> » снимается, пустая «> » разделяет абзацы. */
function quoteText(lines) {
  const paras = [];
  let cur = [];
  for (const raw of lines) {
    const body = raw.replace(/^>\s?/, '').trim();
    if (!body) { if (cur.length) { paras.push(cur.join(' ')); cur = []; } continue; }
    cur.push(body);
  }
  if (cur.length) paras.push(cur.join(' '));
  return paras.join('\n\n');
}

function parseDossier(md) {
  const out = [];
  let variant = null, field = null, declared = null, buf = null;
  const flush = () => {
    if (field && buf && buf.length) out.push({ variant, field, declared, text: quoteText(buf) });
    field = null; buf = null;
  };
  for (const l of md.split(/\r?\n/)) {
    const v = /^### 4\.\d+\.\s*Вариант\s+([АБ])/.exec(l);
    if (v) { flush(); variant = v[1]; continue; }
    const h = /^\*\*(Слоган|Краткое описание|Подробное описание)\*\*\s*\((\d+)\s*символ/i.exec(l);
    if (h) { flush(); field = h[1]; declared = Number(h[2]); buf = []; continue; }
    // Пустая строка между заголовком блока и цитатой блок не закрывает.
    if (!l.trim()) continue;
    if (buf !== null && /^>/.test(l)) { buf.push(l); continue; }
    flush();
  }
  flush();
  return out;
}

