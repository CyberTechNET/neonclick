let bad = 0;
for (const g of GUARDS) {
  const full = fs.readFileSync(path.join(ROOT, g.file), 'utf8');
  /* Два рода контроля. `cut` вырезает абзац — им меряют сторожа, который требует
     от документа наличия факта. `mut` подменяет в документе число — им меряют
     сторожа, который сверяет документ с CFG: вырезанный абзац ничего не доказывает,
     правило «в тексте есть ×1,25» светится зелёным, пока в тексте осталось слово
     «честь», и только подмена цифры показывает, что сторож смотрит на число. */
  let probe = null, label = '';
  if (g.cut) {
    if (!g.cut.test(full)) {
      console.log('  ❌ ' + g.name + '  (абзац-мишень не найден: контроль слеп)');
      bad++;
      continue;
    }
    probe = full.replace(g.cut, '');
    label = 'без абзаца: ';
  } else if (g.mut) {
    const [re, to] = g.mut;
    if (!re.test(full)) {
      console.log('  ❌ ' + g.name + '  (число-мишень не найдено: контроль слеп)');
      bad++;
      continue;
    }
    probe = full.replace(re, to);
    label = 'с подменой: ';
  } else {
    console.log('  ❌ ' + g.name + '  (у контроля нет ни cut, ни mut)');
    bad++;
    continue;
  }
  const onFull = g.rule(full);
  const onProbe = g.rule(probe);
  const alive = onFull === true && onProbe === false;
  if (!alive) bad++;
  console.log((alive ? '  ✅ ' : '  ❌ ') + g.name +
    '  (на документе: ' + onFull + ', ' + label + onProbe + ')');
}

console.log('\n===== КОНТРОЛЬ СТОРОЖЕЙ ' + (GUARDS.length - bad) + ' / ' + GUARDS.length + ' =====');
if (bad) console.log('Сторож мёртв: правило истинно и без сторожего абзаца (или с подменённым числом), либо мишень не найдена. Править регэксп в tools/check-copy.cjs, а не текст документа.');
process.exit(bad ? 1 : 0);
