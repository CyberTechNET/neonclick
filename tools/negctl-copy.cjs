/* ДВУСТОРОННИЙ КОНТРОЛЬ РЕГЭКСПРЕССИЙ check-copy.

   Регэксп по кириллице умеет молча умереть: `\w` — это [A-Za-z0-9_], поэтому
   `списк\w*\s+установк` не матчит «списке установки», и проверка на факт,
   записанный в досье, превращается в украшение. Такой чекер зелёный всегда,
   включая тот прогон, когда факт из документа удалили, — то есть ровно тогда,
   когда он нужен.

   Отсюда правило: проверка считается живой, только если она истинна на
   настоящем документе И ложна на том же документе без абзаца, который она
   сторожит. Односторонний контроль эту мёртвую ветку пропускает.

   Вырезается абзац, а не весь файл: цель — убедиться, что сторож смотрит именно
   на этот факт, а не на что-то случайно оставшееся в тексте. */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const GUARDS = [
  {
    name: 'README: отсутствие приложения в списке установки сообщества',
    file: 'README.md',
    cut: /Предварительное условие[\s\S]*?залогиненным глазом\./,
    rule: (t) => /«Мои приложения»/.test(t) && /ни NeonClick, ни 54836005/i.test(t),
  },
  {
    name: 'README: причины отсутствия перечислены (аккаунт, сообщество, статус)',
    file: 'README.md',
    cut: /Предварительное условие[\s\S]*?залогиненным глазом\./,
    rule: (t) => /два NeonClick/i.test(t) && /Состояние для пользователей/i.test(t),
  },
  {
    name: 'README: отмечено, что факт непроверяем извне',
    file: 'README.md',
    cut: /Предварительное условие[\s\S]*?залогиненным глазом\./,
    rule: (t) => /формой\s+входа/i.test(t),
  },
  {
    name: 'досье: снимок гильдии требует доступности к установке',
    file: 'assets/moderation/application.md',
    cut: /У снимка есть условие[\s\S]*?работы гильдии\./,
    rule: (t) => /«Мои приложения»/.test(t) && /списк\S*\s+установк/i.test(t),
  },
  {
    name: 'досье и README: две причины отсутствия гильдии разведены',
    file: 'README.md',
    cut: /Симптом отсутствующей привязки[\s\S]*?переподключением\./,
    rule: (t) => /запуск не из сообщества/.test(t) && /нет подключения к VK/i.test(t),
  },
  {
    name: 'README: четвёртая причина — тип приложения «Игра»',
    file: 'README.md',
    cut: /4\) Тип приложения[\s\S]*?в досье\./,
    rule: (t) => t.includes('не используется в играх') && t.includes('«Игра»'),
  },
  {
    name: 'досье §5: гильдейский скриншот на карточке-игре недостижим',
    file: 'assets/moderation/application.md',
    cut: /20\.10\.2026 первые три причины[\s\S]*?а не как правильный\./,
    rule: (t) => t.includes('не используется в играх') && t.includes('новый `vk_app_id`'),
  },
  {
    name: 'README п.1: тип назван там, где его выбирают',
    file: 'README.md',
    cut: /В форме создания обязательно[\s\S]*?проверены и сняты\./,
    rule: (t) => t.includes('обязательно выбрать тип «Мини-приложение»'),
  },
  {
    name: 'README п.1: удаление ошибочной карточки — путь, право, необратимость',
    file: 'README.md',
    cut: /Ошибочная карточка не перевыпускается[\s\S]*?всплывающем окне\./,
    rule: (t) => t.includes('dev.vk.com/admin/apps-list') &&
      t.includes('Удалённую игру нельзя восстановить'),
  },
  {
    name: 'README п.1: удаление идёт после регистрации новой карточки',
    file: 'README.md',
    cut: /Порядок важнее скорости[\s\S]*?ни модерации\./,
    rule: (t) => t.includes('сначала новая карточка') && t.includes('потом удаление'),
  },

];

let bad = 0;
for (const g of GUARDS) {
  const full = fs.readFileSync(path.join(ROOT, g.file), 'utf8');
  if (!g.cut.test(full)) {
    console.log('  ❌ ' + g.name + '  (абзац-мишень не найден: контроль слеп)');
    bad++;
    continue;
  }
  const onFull = g.rule(full);
  const onStripped = g.rule(full.replace(g.cut, ''));
  const alive = onFull === true && onStripped === false;
  if (!alive) bad++;
  console.log((alive ? '  ✅ ' : '  ❌ ') + g.name +
    '  (на документе: ' + onFull + ', без абзаца: ' + onStripped + ')');
}

console.log('\n===== КОНТРОЛЬ СТОРОЖЕЙ ' + (GUARDS.length - bad) + ' / ' + GUARDS.length + ' =====');
if (bad) console.log('Сторож мёртв: правило истинно и без сторожего абзаца, либо абзац не найден. Править регэксп в tools/check-copy.cjs, а не текст документа.');
process.exit(bad ? 1 : 0);
